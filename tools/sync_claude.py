#!/usr/bin/env python3
"""Generate the Claude Code mirror (.claude/) from the canonical Antigravity sources (.agents/).

.agents/ is the single source of truth. This script writes:
  .claude/agents/<name>.md                  <- .agents/agents/<name>/agent.md (tools remapped, AG-only keys dropped)
  .claude/skills/<name>/SKILL.md            <- .agents/skills/<name>/SKILL.md (verbatim; same format)
  .claude/rules/sage-governance-prompt.md   <- .agents/rules/sage-governance-prompt.md (frontmatter stripped)

Usage:
  python tools/sync_claude.py           # (re)generate files
  python tools/sync_claude.py --check   # exit 1 if generated files are missing or stale (for CI)
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

ROOT = Path(__file__).resolve().parent.parent

# Antigravity tool -> Claude Code tool. None = no equivalent (dropped).
TOOL_MAP: Dict[str, Optional[str]] = {
    "view_file": "Read",
    "find_by_name": "Glob",
    "list_dir": "Glob",
    "grep_search": "Grep",
    "read_url_content": "WebFetch",
    "search_web": "WebSearch",
    "send_message": None,
    "schedule": None,
    "generate_image": None,
}

BANNER = "<!-- GENERATED by tools/sync_claude.py from {src} - edit the source, then re-run the script. -->\n"


def split_frontmatter(text: str) -> Tuple[List[str], str]:
    """Return (frontmatter lines, body). Raises ValueError when no frontmatter block exists."""
    text = text.replace("\r\n", "\n")
    m = re.match(r"^---\n(.*?)\n---\n?(.*)$", text, re.DOTALL)
    if not m:
        raise ValueError("missing YAML frontmatter")
    return m.group(1).split("\n"), m.group(2)


def scalar(fm: List[str], key: str) -> str:
    for line in fm:
        if line.startswith(f"{key}:"):
            return line.split(":", 1)[1].strip()
    raise ValueError(f"frontmatter key '{key}' not found")


def list_values(fm: List[str], key: str) -> List[str]:
    out: List[str] = []
    inside = False
    for line in fm:
        if line.startswith(f"{key}:"):
            inside = True
            continue
        if inside:
            m = re.match(r"^\s+-\s+(\S+)\s*$", line)
            if m:
                out.append(m.group(1))
            else:
                break
    return out


def map_tools(ag_tools: List[str]) -> List[str]:
    mapped: List[str] = []
    for tool in ag_tools:
        if tool not in TOOL_MAP:
            raise ValueError(f"unmapped Antigravity tool '{tool}' - add it to TOOL_MAP")
        target = TOOL_MAP[tool]
        if target and target not in mapped:
            mapped.append(target)
    return mapped


def render_agent(src_rel: str, text: str) -> str:
    fm, body = split_frontmatter(text)
    name, desc = scalar(fm, "name"), scalar(fm, "description")
    tools = ", ".join(map_tools(list_values(fm, "tools")))
    return f"---\nname: {name}\ndescription: {desc}\ntools: {tools}\n---\n" + BANNER.format(src=src_rel) + body


def render_skill(text: str) -> str:
    return text.replace("\r\n", "\n")


def render_rule(src_rel: str, text: str) -> str:
    _, body = split_frontmatter(text)
    return BANNER.format(src=src_rel) + body.lstrip("\n")


def expected_outputs() -> Dict[str, str]:
    outputs: Dict[str, str] = {}
    for agent in sorted((ROOT / ".agents" / "agents").glob("*/agent.md")):
        rel = agent.relative_to(ROOT).as_posix()
        outputs[f".claude/agents/{agent.parent.name}.md"] = render_agent(rel, agent.read_text(encoding="utf-8"))
    for skill in sorted((ROOT / ".agents" / "skills").glob("*/SKILL.md")):
        outputs[f".claude/skills/{skill.parent.name}/SKILL.md"] = render_skill(skill.read_text(encoding="utf-8"))
    for rule in sorted((ROOT / ".agents" / "rules").glob("*.md")):
        rel = rule.relative_to(ROOT).as_posix()
        outputs[f".claude/rules/{rule.name}"] = render_rule(rel, rule.read_text(encoding="utf-8"))
    return outputs


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify generated files are current; do not write")
    args = ap.parse_args()

    outputs = expected_outputs()
    stale: List[str] = []
    for rel, content in outputs.items():
        path = ROOT / rel
        current = path.read_bytes().decode("utf-8").replace("\r\n", "\n") if path.exists() else None
        if current != content:
            stale.append(rel)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(content.encode("utf-8"))

    orphans = []
    claude = ROOT / ".claude"
    if claude.exists():
        known = set(outputs)
        orphans = [
            p.relative_to(ROOT).as_posix()
            for p in claude.rglob("*")
            if p.is_file() and p.relative_to(ROOT).as_posix() not in known
            and not p.name.startswith("settings")
        ]

    if args.check:
        for rel in stale:
            print(f"STALE/MISSING: {rel}")
        for rel in orphans:
            print(f"ORPHAN (no .agents source): {rel}")
        if stale or orphans:
            print("Run: python tools/sync_claude.py")
            return 1
        print(f"OK: {len(outputs)} Claude Code files match .agents/ sources.")
        return 0

    print(f"Wrote {len(stale)} file(s); {len(outputs) - len(stale)} already current.")
    for rel in orphans:
        print(f"WARNING: orphan {rel} has no .agents source")
    return 0


if __name__ == "__main__":
    sys.exit(main())
