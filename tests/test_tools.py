# ---------------- sync_claude
def test_map_tools_translates_and_drops():
    out = sc.map_tools(["send_message", "find_by_name", "list_dir", "grep_search", "view_file", "schedule"])
    assert out == ["Glob", "Grep", "Read"]  # list_dir dedupes into Glob; unsupported tools dropped


def test_map_tools_unmapped_raises():
    with pytest.raises(ValueError, match="unmapped"):
        sc.map_tools(["teleport"])


AGENT = """---
name: demo
description: A demo agent for tests.
tools:
  - view_file
  - search_web
  - generate_image
hidden: true
inheritCustomizations: false
inheritMcp: false
---

# Body
Hello
"""


def test_render_agent_strips_antigravity_keys_and_adds_banner():
    out = sc.render_agent(".agents/agents/demo/agent.md", AGENT)
    head, _, rest = out.partition("\n---\n")
    assert "tools: Read, WebSearch" in head
    for gone in ("hidden", "inheritCustomizations", "inheritMcp", "generate_image"):
        assert gone not in out
    assert "GENERATED by tools/sync_claude.py from .agents/agents/demo/agent.md" in rest
    assert rest.rstrip().endswith("Hello")


def test_render_agent_handles_crlf():
    assert sc.render_agent("x", AGENT.replace("\n", "\r\n")) == sc.render_agent("x", AGENT)


def test_render_rule_drops_frontmatter():
    out = sc.render_rule("src.md", "---\nname: r\ndescription: d\n---\n\n# Rule\n")
    assert out.startswith("<!-- GENERATED") and "name: r" not in out and "# Rule" in out


def test_split_frontmatter_requires_block():
    with pytest.raises(ValueError):
        sc.split_frontmatter("# no frontmatter")


def _fake_repo(tmp_path, monkeypatch):
    (tmp_path / ".agents/agents/demo").mkdir(parents=True)
    (tmp_path / ".agents/agents/demo/agent.md").write_text(AGENT, encoding="utf-8")
    (tmp_path / ".agents/skills/s1").mkdir(parents=True)
    (tmp_path / ".agents/skills/s1/SKILL.md").write_text(
        "---\nname: s1\ndescription: skill one\n---\nBody\n", encoding="utf-8"
    )
    (tmp_path / ".agents/rules").mkdir(parents=True)
    (tmp_path / ".agents/rules/r.md").write_text("---\nname: r\ndescription: d\n---\n# R\n", encoding="utf-8")
    monkeypatch.setattr(sc, "ROOT", tmp_path)
    return tmp_path


def run_main(monkeypatch, *argv):
    monkeypatch.setattr("sys.argv", ["sync_claude.py", *argv])
    return sc.main()


def test_check_detects_missing_then_passes_after_sync(tmp_path, monkeypatch, capsys):
    root = _fake_repo(tmp_path, monkeypatch)
    assert run_main(monkeypatch, "--check") == 1
    assert "STALE/MISSING: .claude/agents/demo.md" in capsys.readouterr().out
    assert run_main(monkeypatch) == 0
    assert (root / ".claude/skills/s1/SKILL.md").exists() and (root / ".claude/rules/r.md").exists()
    assert run_main(monkeypatch, "--check") == 0


def test_check_detects_stale_and_orphan(tmp_path, monkeypatch, capsys):
    root = _fake_repo(tmp_path, monkeypatch)
    run_main(monkeypatch)
    (root / ".claude/agents/demo.md").write_text("tampered", encoding="utf-8")
    (root / ".claude/agents/extra.md").write_text("orphan", encoding="utf-8")
    (root / ".claude/settings.local.json").write_text("{}", encoding="utf-8")  # ignored by design
    assert run_main(monkeypatch, "--check") == 1
    out = capsys.readouterr().out
    assert "STALE/MISSING: .claude/agents/demo.md" in out
    assert "ORPHAN (no .agents source): .claude/agents/extra.md" in out
    assert "settings.local.json" not in out


def test_real_mirror_is_current():
    assert sc.ROOT.joinpath(".claude").exists()
    for rel, content in sc.expected_outputs().items():
        on_disk = (sc.ROOT / rel).read_bytes().decode("utf-8").replace("\r\n", "\n")
        assert on_disk == content, rel


# ---------------- build_manifest
def test_digest_is_line_ending_independent(tmp_path):
    a, b = tmp_path / "a", tmp_path / "b"
    a.write_bytes(b"one\r\ntwo\r\n")
    b.write_bytes(b"one\ntwo\n")
    assert bm.digest(a) == bm.digest(b) == hashlib.sha256(b"one\ntwo\n").hexdigest()


def test_manifest_matches_repo_and_covers_expected_files():
    data = json.loads(bm.build())
    assert data["algorithm"] == "sha256"
    assert set(data["files"]) == set(bm.EXPECTED_FILES)
    assert data["version"] == bm.VERSION_FILE.read_text(encoding="utf-8").strip()
    assert bm.MANIFEST.read_bytes().decode("utf-8").replace("\r\n", "\n") == bm.build()
