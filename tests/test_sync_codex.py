import tomllib

import pytest

import sync_codex as sx

AGENT = """---
name: demo
description: A "demo" agent for tests.
tools:
  - view_file
  - list_dir
  - find_by_name
  - search_web
  - generate_image
hidden: true
inheritCustomizations: false
inheritMcp: false
---

# Body
Math stays literal: $\\rightarrow$ and C:\\path
"""

GEMINI = "# Ledger\r\nLiving notes\r\n"
RULE = "---\nname: r\ndescription: d\n---\n\n# Rule body\n"


def test_capabilities_translate_dedupe_and_drop():
    assert sx.capabilities(["view_file", "list_dir", "find_by_name", "schedule"]) == [
        "read files",
        "find and list files",
    ]


def test_capabilities_unmapped_raises():
    with pytest.raises(ValueError, match="unmapped"):
        sx.capabilities(["teleport"])


def test_render_agent_is_valid_toml_with_body_verbatim():
    out = sx.render_agent(".agents/agents/demo/agent.md", AGENT)
    assert out.startswith("# GENERATED by tools/sync_codex.py from .agents/agents/demo/agent.md")
    data = tomllib.loads(out)
    assert set(data) == {"name", "description", "developer_instructions"}
    assert data["name"] == "demo"
    assert data["description"] == 'A "demo" agent for tests.'
    instructions = data["developer_instructions"]
    assert instructions.startswith("Codex note: this is a read-only advisory agent.")
    assert "read files, find and list files, search the web" in instructions
    assert "Math stays literal: $\\rightarrow$ and C:\\path" in instructions
    for gone in ("hidden", "inheritCustomizations", "generate_image"):
        assert gone not in out


def test_render_agent_handles_crlf():
    assert sx.render_agent("x", AGENT.replace("\n", "\r\n")) == sx.render_agent("x", AGENT)


def test_render_agent_rejects_triple_quote_body():
    with pytest.raises(ValueError, match="'''"):
        sx.render_agent("x", AGENT + "\n'''\n")


def test_render_agents_md_points_to_ledger_and_rules():
    out = sx.render_agents_md([".agents/rules/r.md"], ["aegis_best_practice", "sage_governance"], 7)
    assert out.startswith("<!-- GENERATED by tools/sync_codex.py")
    assert "1. `GEMINI.md`" in out and "2. `.agents/rules/r.md`" in out
    assert "the 7 governance skills" in out and "the 2 specialist agents (AEGIS, SAGE)" in out


def _fake_repo(tmp_path, monkeypatch):
    (tmp_path / ".agents/agents/demo").mkdir(parents=True)
    (tmp_path / ".agents/agents/demo/agent.md").write_text(AGENT, encoding="utf-8")
    (tmp_path / ".agents/skills/s1").mkdir(parents=True)
    (tmp_path / ".agents/skills/s1/SKILL.md").write_text("---\nname: s1\ndescription: d\n---\n", encoding="utf-8")
    (tmp_path / ".agents/rules").mkdir(parents=True)
    (tmp_path / ".agents/rules/r.md").write_text(RULE, encoding="utf-8")
    (tmp_path / "GEMINI.md").write_text(GEMINI, encoding="utf-8")
    monkeypatch.setattr(sx, "ROOT", tmp_path)
    return tmp_path


def run_main(monkeypatch, *argv):
    monkeypatch.setattr("sys.argv", ["sync_codex.py", *argv])
    return sx.main()


def test_check_detects_missing_then_passes_after_sync(tmp_path, monkeypatch, capsys):
    root = _fake_repo(tmp_path, monkeypatch)
    assert run_main(monkeypatch, "--check") == 1
    out = capsys.readouterr().out
    assert "STALE/MISSING: .codex/agents/demo.toml" in out and "STALE/MISSING: AGENTS.md" in out
    assert run_main(monkeypatch) == 0
    assert (root / "AGENTS.md").exists()
    assert not (root / ".codex/skills").exists()  # Codex reads .agents/skills natively
    assert run_main(monkeypatch, "--check") == 0


def test_agents_md_does_not_copy_shared_context(tmp_path, monkeypatch):
    # Antigravity loads AGENTS.md alongside GEMINI.md and .agents/rules/, so copying them would double-load.
    root = _fake_repo(tmp_path, monkeypatch)
    run_main(monkeypatch)
    agents_md = (root / "AGENTS.md").read_text(encoding="utf-8")
    assert "# Ledger" not in agents_md and "# Rule body" not in agents_md
    (root / "GEMINI.md").write_text("# Ledger\nUpdated\n", encoding="utf-8")
    assert run_main(monkeypatch, "--check") == 0


def test_check_detects_orphan_but_ignores_codex_config(tmp_path, monkeypatch, capsys):
    root = _fake_repo(tmp_path, monkeypatch)
    run_main(monkeypatch)
    (root / ".codex/agents/extra.toml").write_text('name = "x"\n', encoding="utf-8")
    (root / ".codex/config.toml").write_text("", encoding="utf-8")  # user's own Codex config
    assert run_main(monkeypatch, "--check") == 1
    out = capsys.readouterr().out
    assert "ORPHAN (no .agents source): .codex/agents/extra.toml" in out
    assert "config.toml" not in out


def test_real_codex_files_are_current_and_parse():
    for rel, content in sx.expected_outputs().items():
        on_disk = (sx.ROOT / rel).read_bytes().decode("utf-8").replace("\r\n", "\n")
        assert on_disk == content, rel
        if rel.endswith(".toml"):
            assert tomllib.loads(on_disk)["name"] == rel.rsplit("/", 1)[1][: -len(".toml")]
