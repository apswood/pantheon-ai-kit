#!/usr/bin/env python3
"""Generate the OpenAI Codex files (AGENTS.md, .codex/agents/) from the canonical sources.

Codex discovers skills in .agents/skills/ natively, so skills need no mirror. This script writes:
  AGENTS.md                      <- names in .agents/ (tells Codex to read GEMINI.md and .agents/rules/*.md)
  .codex/agents/<name>.toml      <- .agents/agents/<name>/agent.md (body becomes developer_instructions)

AGENTS.md points to the shared context instead of copying it: Antigravity reads AGENTS.md as well as GEMINI.md and
.agents/rules/, so an inlined copy would load the same instructions twice there.

Codex custom agents have no per-tool allowlist and cannot set their own sandbox, so the Antigravity tool list is
turned into a read-only instruction at the top of developer_instructions instead.

Usage:
  python tools/sync_codex.py           # (re)generate files
  python tools/sync_codex.py --check   # exit 1 if generated files are missing or stale (for CI)
  python tools/sync_codex.py --target-dir ../ws --only sage_governance,ticket-backlog-governance
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Dict, List, Optional, Set

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sync_claude import list_values, parse_only, scalar, split_frontmatter  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

# Antigravity tool -> plain-language capability for the Codex instruction. None = no equivalent (dropped).
CAPABILITY_MAP: Dict[str, Optional[str]] = {
    "view_file": "read files",
    "find_by_name": "find and list files",
    "list_dir": "find and list files",
    "grep_search": "search file contents",
    "read_url_content": "fetch web pages",
    "search_web": "search the web",
    "send_message": None,
    "schedule": None,
    "generate_image": None,
}

TOML_BANNER = "# GENERATED by tools/sync_codex.py from {src} - edit the source, then re-run the script.\n"

AGENTS_MD = """<!-- GENERATED by tools/sync_codex.py - edit .agents/ or the template in the script, then re-run it. -->
# AGENTS.md - PANTHEON AI Kit (OpenAI Codex entry point)

This workspace works with **Google Antigravity**, **Claude Code** and **OpenAI Codex**. Antigravity and Claude Code
already load the shared context; this file is for Codex, which cannot import files. It points to the sources instead
of copying them, because Antigravity also reads `AGENTS.md` and would otherwise load the same instructions twice.

## Read first

Before starting any task in this workspace, read these files in full and follow them as project instructions:

1. `GEMINI.md` - the shared living handover ledger (architecture, metric baselines, runbook, milestones).
{rule_lines}

When asked to update the handover ledger, edit `GEMINI.md`.

## Codex layout

- `.agents/skills/` - the {skill_count} governance skills. Codex reads this folder natively (no mirror); mention one with
  `$ticket-backlog-governance` or pick from `/skills`.
- `.codex/agents/` - the {agent_count} specialist agents ({agent_names}). Ask Codex to spawn one by name, e.g.
  "Spawn aegis_best_practice to audit this FortiGate config".
- **Do not hand-edit `AGENTS.md` or `.codex/agents/`.** They are generated from `.agents/`; edit the agents, skills
  or rules there, then run `python tools/sync_codex.py` (CI runs `--check` and fails on drift).

## Working rules

- Treat `.env` and `.custom_blocklist.json` as secrets: never read, print, or commit them.
- Run `python validate_kit.py` before committing; it must exit 0.
"""


def capabilities(ag_tools: List[str]) -> List[str]:
    caps: List[str] = []
    for tool in ag_tools:
        if tool not in CAPABILITY_MAP:
            raise ValueError(f"unmapped Antigravity tool '{tool}' - add it to CAPABILITY_MAP")
        cap = CAPABILITY_MAP[tool]
        if cap and cap not in caps:
            caps.append(cap)
    return caps


def toml_basic(value: str) -> str:
    """A TOML basic string; JSON string escaping is a valid subset of TOML's."""
    return json.dumps(value, ensure_ascii=False)


def toml_multiline_literal(value: str) -> str:
    if "'''" in value:
        raise ValueError("agent body contains ''' and cannot be written as a TOML literal string")
    # A newline straight after the opening delimiter is trimmed by TOML parsers.
    return "'''\n" + value.rstrip("\n") + "\n'''"


def render_agent(src_rel: str, text: str) -> str:
    fm, body = split_frontmatter(text)
    name, desc = scalar(fm, "name"), scalar(fm, "description")
    caps = capabilities(list_values(fm, "tools"))
    preamble = (
        f"Codex note: this is a read-only advisory agent. In the source kit it may only {', '.join(caps)}. "
        "Do not create, edit or delete files, and only run shell commands that inspect state.\n\n"
    )
    return (
        TOML_BANNER.format(src=src_rel)
        + f"name = {toml_basic(name)}\n"
        + f"description = {toml_basic(desc)}\n"
        + f"developer_instructions = {toml_multiline_literal(preamble + body.lstrip(chr(10)))}\n"
    )


def render_agents_md(rule_paths: List[str], agent_names: List[str], skill_count: int) -> str:
    rule_lines = "\n".join(
        f"{i}. `{path}` - always-on governance rule (formulas, thresholds, language standards)."
        for i, path in enumerate(rule_paths, start=2)
    )
    return AGENTS_MD.format(
        rule_lines=rule_lines,
        skill_count=skill_count,
        agent_count=len(agent_names),
        agent_names=", ".join(n.split("_")[0].upper() for n in agent_names),
    )


def expected_outputs(
    src: Optional[Path] = None, only: Optional[Set[str]] = None, extra_rules: Optional[List[str]] = None
) -> Dict[str, str]:
    """Generated files for the agents under src (default: this repo), limited to `only` names if given.

    extra_rules are rule paths that exist only in the target workspace (e.g. the generated local-baselines rule).
    """
    src = src or ROOT
    outputs: Dict[str, str] = {}
    agents = [a for a in sorted((src / ".agents" / "agents").glob("*/agent.md")) if only is None or a.parent.name in only]
    for agent in agents:
        rel = agent.relative_to(src).as_posix()
        outputs[f".codex/agents/{agent.parent.name}.toml"] = render_agent(rel, agent.read_text(encoding="utf-8"))

    rules = [r.relative_to(src).as_posix() for r in sorted((src / ".agents" / "rules").glob("*.md"))]
    skills = [s for s in (src / ".agents" / "skills").glob("*/SKILL.md") if only is None or s.parent.name in only]
    outputs["AGENTS.md"] = render_agents_md(
        rules + [r for r in (extra_rules or []) if r not in rules],
        [a.parent.name for a in agents],
        len(skills),
    )
    return outputs


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify generated files are current; do not write")
    ap.add_argument("--target-dir", help="write into this workspace instead of the repo (sources stay in the repo)")
    ap.add_argument("--only", help="comma-separated agent/skill folder names to include (default: all)")
    args = ap.parse_args()

    out_root = Path(args.target_dir).resolve() if args.target_dir else ROOT
    outputs = expected_outputs(only=parse_only(args.only))
    stale: List[str] = []
    for rel, content in outputs.items():
        path = out_root / rel
        current = path.read_bytes().decode("utf-8").replace("\r\n", "\n") if path.exists() else None
        if current != content:
            stale.append(rel)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(content.encode("utf-8"))

    orphans = []
    agents_dir = out_root / ".codex" / "agents"
    if agents_dir.exists():
        known = set(outputs)
        orphans = [
            p.relative_to(out_root).as_posix()
            for p in agents_dir.rglob("*")
            if p.is_file() and p.relative_to(out_root).as_posix() not in known
        ]

    if args.check:
        for rel in stale:
            print(f"STALE/MISSING: {rel}")
        for rel in orphans:
            print(f"ORPHAN (no .agents source): {rel}")
        if stale or orphans:
            print("Run: python tools/sync_codex.py")
            return 1
        print(f"OK: {len(outputs)} Codex files match .agents/ sources.")
        return 0

    print(f"Wrote {len(stale)} file(s); {len(outputs) - len(stale)} already current.")
    for rel in orphans:
        print(f"WARNING: orphan {rel} has no .agents source")
    return 0


if __name__ == "__main__":
    sys.exit(main())
